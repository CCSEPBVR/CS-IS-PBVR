SLAC_EXTERIOR = (0, 123, 171, 170, 159, -1, -1, -1, -1)


def _format_value(value):
    return str(value) if isinstance(value, int) else format(value, ".17g")


def _format_values(values, values_per_line=8):
    lines = []
    for begin in range(0, len(values), values_per_line):
        lines.append(
            "    "
            + ", ".join(
                _format_value(value)
                for value in values[begin : begin + values_per_line]
            )
        )
    return ",\n".join(lines)


def _coordinates():
    values = []
    for z_index in range(4):
        for y_index in range(4):
            for x_index in range(12):
                values.extend((x_index, y_index, z_index))
    return values


def _mode_values(mode_index):
    values = []
    for _z_index in range(4):
        for _y_index in range(4):
            for x_index in range(12):
                values.append(270.0 + 5.0 * mode_index + 20.0 * x_index / 11.0)
    return values


def _mode_cdl(filename, mode_index):
    return f"""netcdf {filename} {{
dimensions:
    ncoord = 192 ;
    three = 3 ;
variables:
    double coords(ncoord, three) ;
    double temperature(ncoord) ;
        temperature:units = "K" ;
    double frequency ;

// global attributes:
        :title = "Simple linear temperature field for vtkSLACReader" ;
data:
    coords =
{_format_values(_coordinates(), 3)} ;
    temperature =
{_format_values(_mode_values(mode_index))} ;
    frequency = {mode_index} ;
}}
"""


def _volume_cdl(filename):
    interior = [
        value
        for tetrahedron in SLAC_INTERIOR_TETRAHEDRA
        for value in (0, *tetrahedron)
    ]
    coordinates = _coordinates()
    return f"""netcdf {filename} {{
dimensions:
    ncoord = 192 ;
    three = 3 ;
    ntet_interior = 593 ;
    five = 5 ;
    ntet_exterior = 1 ;
    nine = 9 ;
variables:
    int tetrahedron_interior(ntet_interior, five) ;
    double coords(ncoord, three) ;
    int tetrahedron_exterior(ntet_exterior, nine) ;

// global attributes:
        :title = "Simple rectangular vtkSLACReader volume sample" ;
data:
    tetrahedron_interior =
{_format_values(interior, 5)} ;
    coords =
{_format_values(coordinates, 3)} ;
    tetrahedron_exterior =
{_format_values(SLAC_EXTERIOR, 9)} ;
}}
"""


def generate(output_dir, writer):
    files = []
    for mode_index in range(3):
        filename = f"vtkSLACReader_mode_{mode_index}.ncdf"
        files.append(
            writer(output_dir, filename, "cdf-2", _mode_cdl(filename, mode_index))
        )

    filename = "vtkSLACReader_volume.ncdf"
    files.append(writer(output_dir, filename, "classic", _volume_cdl(filename)))
    return files
